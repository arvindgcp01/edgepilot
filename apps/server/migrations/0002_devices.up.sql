-- 0002_devices — enrollment, device registry, certificates, inventory.

-- ---------------------------------------------------------------------------
-- Enrollment tokens
-- ---------------------------------------------------------------------------

CREATE TABLE enrollment_tokens (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id       uuid        NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
    -- Only the SHA-256 of the token is persisted; the plaintext is shown once.
    token_hash   bytea       NOT NULL UNIQUE CHECK (octet_length(token_hash) = 32),
    -- Non-secret prefix (e.g. "ep_enroll_9f3a") so the UI can identify a token.
    token_prefix text        NOT NULL,
    description  text        NOT NULL DEFAULT '',
    -- NULL = unlimited uses within the TTL.
    max_uses     integer     CHECK (max_uses IS NULL OR max_uses > 0),
    use_count    integer     NOT NULL DEFAULT 0,
    -- When false, enrolled devices land in enrollment_state='pending' and receive
    -- no commands until an admin approves them.
    auto_approve boolean     NOT NULL DEFAULT false,
    -- Labels stamped onto every device enrolled with this token (site, rollout ring).
    labels       jsonb       NOT NULL DEFAULT '{}'::jsonb,
    expires_at   timestamptz NOT NULL,
    revoked_at   timestamptz,
    created_by   uuid        REFERENCES users (id) ON DELETE SET NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    CHECK (max_uses IS NULL OR use_count <= max_uses)
);
CREATE INDEX enrollment_tokens_org_idx ON enrollment_tokens (org_id, created_at DESC);

-- ---------------------------------------------------------------------------
-- Devices
-- ---------------------------------------------------------------------------

CREATE TABLE devices (
    -- UUIDv7, generated by the agent on first boot and accepted by the server.
    -- Time-ordered so index locality holds as the fleet grows.
    id                 uuid        PRIMARY KEY,
    org_id             uuid        NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,

    -- Identity
    hostname           text        NOT NULL DEFAULT '',
    serial_number      text        NOT NULL,
    hardware_uuid      text,

    -- Hardware, refreshed from inventory
    model_identifier   text,                       -- Macmini9,1 / Mac14,13
    model_name         text,                       -- "Mac mini" / "Mac Studio"
    chip               text,                       -- "Apple M2 Max"
    arch               text        CHECK (arch IS NULL OR arch IN ('arm64', 'x86_64')),
    cpu_cores          smallint    CHECK (cpu_cores IS NULL OR cpu_cores > 0),
    cpu_performance_cores smallint,
    cpu_efficiency_cores  smallint,
    memory_bytes       bigint      CHECK (memory_bytes IS NULL OR memory_bytes > 0),
    disk_total_bytes   bigint      CHECK (disk_total_bytes IS NULL OR disk_total_bytes > 0),

    -- Software
    os_name            text        NOT NULL DEFAULT 'macOS',
    os_version         text,                       -- 15.3.1
    os_build           text,                       -- 24D70
    agent_version      text,

    -- Network, refreshed on every connect
    local_ip           inet,
    public_ip          inet,
    primary_mac        macaddr,

    -- Operational placement
    site               text        NOT NULL DEFAULT '',
    notes              text        NOT NULL DEFAULT '',
    labels             jsonb       NOT NULL DEFAULT '{}'::jsonb,

    status             text        NOT NULL DEFAULT 'pending'
                                   CHECK (status IN ('pending', 'online', 'offline',
                                                     'degraded', 'decommissioned')),
    enrollment_state   text        NOT NULL DEFAULT 'pending'
                                   CHECK (enrollment_state IN ('pending', 'approved',
                                                               'rejected', 'revoked')),
    -- Per-device security policy. allow_custom_scripts=false makes the agent refuse
    -- signed custom scripts outright, regardless of server-side approval.
    allow_custom_scripts boolean   NOT NULL DEFAULT false,

    -- Denormalised for the fleet table; kept current by the metrics flusher so the
    -- dashboard's hottest query never joins device_metrics.
    last_cpu_percent   real,
    last_memory_percent real,
    last_disk_percent  real,

    first_enrolled_at  timestamptz,
    last_seen_at       timestamptz,
    last_boot_at       timestamptz,
    -- Which server replica currently owns the agent stream. Redis is authoritative;
    -- this column exists for operator debugging.
    connected_replica  text,

    enrolled_by_token  uuid        REFERENCES enrollment_tokens (id) ON DELETE SET NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    deleted_at         timestamptz
);
-- A serial may be re-enrolled only after the prior record is soft-deleted.
CREATE UNIQUE INDEX devices_org_serial_key ON devices (org_id, serial_number)
    WHERE deleted_at IS NULL;
CREATE INDEX devices_org_status_idx    ON devices (org_id, status)          WHERE deleted_at IS NULL;
CREATE INDEX devices_org_lastseen_idx  ON devices (org_id, last_seen_at DESC NULLS LAST)
                                                                            WHERE deleted_at IS NULL;
CREATE INDEX devices_labels_idx        ON devices USING gin (labels jsonb_path_ops);
CREATE INDEX devices_hostname_trgm_idx ON devices USING gin (hostname gin_trgm_ops);
CREATE INDEX devices_pending_idx       ON devices (org_id) WHERE enrollment_state = 'pending';
CREATE TRIGGER devices_updated_at BEFORE UPDATE ON devices
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ---------------------------------------------------------------------------
-- Device certificates — one row per issued mTLS client certificate
-- ---------------------------------------------------------------------------

CREATE TABLE device_certificates (
    id                 uuid          PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id          uuid          NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    serial             numeric(40,0) NOT NULL UNIQUE,     -- x509 serial number
    fingerprint_sha256 bytea         NOT NULL UNIQUE CHECK (octet_length(fingerprint_sha256) = 32),
    public_key_der     bytea         NOT NULL,
    certificate_pem    text          NOT NULL,
    not_before         timestamptz   NOT NULL,
    not_after          timestamptz   NOT NULL,
    -- 'enrollment' for the first cert, 'renewal' for certs issued over the stream.
    issued_via         text          NOT NULL CHECK (issued_via IN ('enrollment', 'renewal')),
    revoked_at         timestamptz,
    revoked_reason     text,
    revoked_by         uuid          REFERENCES users (id) ON DELETE SET NULL,
    created_at         timestamptz   NOT NULL DEFAULT now(),
    CHECK (not_after > not_before)
);
CREATE INDEX device_certificates_device_idx ON device_certificates (device_id, not_after DESC);
-- Drives the in-memory revocation set the mTLS verify callback consults.
CREATE INDEX device_certificates_revoked_idx ON device_certificates (revoked_at)
    WHERE revoked_at IS NOT NULL;

-- ---------------------------------------------------------------------------
-- Device inventory — versioned snapshots, one row per section per collection
-- ---------------------------------------------------------------------------

CREATE TABLE device_inventory (
    id           uuid        PRIMARY KEY DEFAULT gen_random_uuid(),
    device_id    uuid        NOT NULL REFERENCES devices (id) ON DELETE CASCADE,
    kind         text        NOT NULL CHECK (kind IN ('system', 'hardware', 'network',
                                                      'storage', 'applications',
                                                      'services', 'security', 'peripherals')),
    payload      jsonb       NOT NULL,
    -- SHA-256 of the canonical payload. The agent sends a section only when its
    -- checksum changed, so a stable device writes almost nothing between full refreshes.
    checksum     bytea       NOT NULL CHECK (octet_length(checksum) = 32),
    collected_at timestamptz NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    UNIQUE (device_id, kind, checksum)
);
-- Serves "give me the current inventory" via DISTINCT ON (kind) ... ORDER BY collected_at DESC.
CREATE INDEX device_inventory_current_idx ON device_inventory (device_id, kind, collected_at DESC);
CREATE INDEX device_inventory_payload_idx ON device_inventory USING gin (payload jsonb_path_ops);
